"""Collect every topic's interview questions into INTERVIEW_QUESTIONS.md.

    python tools/build_interview_questions.py

Each topic README keeps its own questions; this script gathers them into one
page for revision. Answers are wrapped in <details> so they stay hidden until
clicked: try to answer first, then check.

Run it again whenever a topic's questions change, so the page never drifts
out of date.
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "INTERVIEW_QUESTIONS.md"

QUESTION = re.compile(r"^\*\*(\d+)\.\s+(.+?)\*\*\s*$")
SECTION_START = re.compile(r"^## Interview (questions|practice.*)$", re.IGNORECASE)


def topic_title(readme: str) -> str:
    """'# 05 · Functions' -> '05 · Functions'"""
    first = next(line for line in readme.splitlines() if line.startswith("# "))
    return first[2:].strip()


def sections(readme: str) -> list[tuple[str, list[str]]]:
    """Return (heading, lines) for each interview section, up to the next '---' or '## '."""
    found, current, lines = [], None, []
    for line in readme.splitlines():
        if SECTION_START.match(line):
            if current:
                found.append((current, lines))
            current, lines = line[3:].strip(), []
        elif current and (line.strip() == "---" or line.startswith("## ")):
            found.append((current, lines))
            current, lines = None, []
        elif current:
            lines.append(line)
    if current:
        found.append((current, lines))
    return found


def question_html(text: str) -> str:
    """GitHub doesn't apply Markdown inside HTML tags, so `code` must become <code>."""
    parts = text.split("`")
    return "".join(html.escape(part) if i % 2 == 0 else f"<code>{html.escape(part)}</code>"
                   for i, part in enumerate(parts))


def to_markdown(lines: list[str]) -> tuple[str, int]:
    """Turn '**1. Question?**' + answer lines into a question with a hidden answer."""
    out, count, question, answer = [], 0, None, []

    def flush():
        nonlocal count
        if question:
            count += 1
            body = "\n".join(answer).strip()
            out.append(f"<details>\n<summary><b>{question}</b></summary>\n\n{body}\n\n</details>\n")

    for line in lines:
        match = QUESTION.match(line)
        if match:
            flush()
            question, answer = f"{match.group(1)}. {question_html(match.group(2))}", []
        elif question:
            answer.append(line)
        else:
            out.append(line)  # sections without numbered questions are kept as they are
    flush()
    return "\n".join(out).strip(), count


def main() -> None:
    parts, total, rows = [], 0, []
    for readme_path in sorted(ROOT.glob("[0-9][0-9]_*/README.md")):
        readme = readme_path.read_text(encoding="utf-8")
        found = sections(readme)
        if not found:
            continue
        title = topic_title(readme)
        folder = readme_path.parent.name
        anchor = re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")
        topic_count = 0
        body = [f"## {title}\n", f"📖 Notes: [{folder}/README.md]({folder}/README.md)\n"]
        for heading, lines in found:
            text, count = to_markdown(lines)
            topic_count += count
            if not heading.lower().startswith("interview questions"):
                body.append(f"### {heading}\n")
            body.append(text + "\n")
        total += topic_count
        rows.append(f"| [{title}](#{anchor}) | {topic_count or 'Explain-your-project practice'} |")
        parts.append("\n".join(body))

    header = f"""# Interview Questions: Python & Data Science

All **{total} interview questions** from this repo in one place, for quick revision.
Each topic's README has the same questions next to the notes that explain them.

**How to use this page:** read a question, answer it **out loud** without looking, then click it to check your answer. If you get one wrong, go back to that topic's notes.

> This page is generated by [tools/build_interview_questions.py](tools/build_interview_questions.py). Edit the topic READMEs, not this file.

| Topic | Questions |
|-------|-----------|
{chr(10).join(rows)}

---
"""
    OUTPUT.write_text(header + "\n\n---\n\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.name}: {total} questions from {len(parts)} topics")


if __name__ == "__main__":
    main()
